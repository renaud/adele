"""Write checks.yaml of the MeteoSwiss station datasets from the figures that match.

Reads qa/published_figures_meteoswiss_matched.csv (written by published_check_meteoswiss.py) and
qa/klimabulletin_urls.csv. A figure becomes a check of a dataset when the variant of that dataset
matches it (within half a unit of the last published digit):

  meteoswiss_smn_daily    temperature (daily), sunshine (daily), precipitation (daily_06utc)
  meteoswiss_smn_hourly   the same from the hourly table, from 2018 on (before, an hour runs
                          from minute 40, and a year of hours doesn't start on 1 January 00:00)
  meteoswiss_smn_tenmin   sunshine (tenmin)
  meteoswiss_nime_daily   precipitation (nime): the stations of the manual network

Usage: python -I write_checks_meteoswiss.py   (from anywhere; paths are relative to the repo)
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
QA = ROOT / "qa"

KINDS = {"temperature_mean_c": ("temperature", "mean temperature", "°C"),
         "sunshine_h": ("sunshine", "sunshine duration", "h"),
         "precipitation_mm": ("precipitation", "precipitation", "mm"),
         "fresh_snow_max_cm": ("fresh_snow_max", "largest fresh snow of one day", "cm")}
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December"]
# dataset --> {kind: (variant, table, SQL expression)}
PLAN = {
    "meteoswiss_smn_daily": {
        "temperature_mean_c": ("daily", "measurements", "avg(temperature)"),
        "sunshine_h": ("daily", "measurements", "sum(sunshine) / 60"),
        "precipitation_mm": ("daily_06utc", "measurements", "sum(precipitation_06utc)"),
    },
    "meteoswiss_smn_hourly": {
        "temperature_mean_c": ("hourly", "measurements", "avg(temperature)"),
        "sunshine_h": ("hourly", "measurements", "sum(sunshine) / 60"),
        "precipitation_mm": ("hourly_06utc", "measurements", "sum(precipitation)"),
    },
    "meteoswiss_smn_tenmin": {"sunshine_h": ("tenmin", "measurements", "sum(sunshine) / 60")},
    "meteoswiss_nime_daily": {"precipitation_mm": ("nime", "measurements", "sum(precipitation)"),
                              "fresh_snow_max_cm": ("nime_max", "measurements", "max(fresh_snow)")},
}
HOW = {  # (variant, kind) --> how the stored rows give the figure
    ("daily", "temperature_mean_c"): "mean of the daily means, days by reference_date (UTC dates)",
    ("daily", "sunshine_h"): "sum of the daily values / 60, days by reference_date (UTC dates)",
    ("daily_06utc", "precipitation_mm"): "sum of precipitation_06utc (days of 06 to 06 UTC) by reference_date",
    ("hourly", "temperature_mean_c"): "mean of the hourly means, hours of the period in UTC",
    ("hourly", "sunshine_h"): "sum of the hourly values / 60, hours of the period in UTC",
    ("hourly_06utc", "precipitation_mm"): "sum of the hours from 06 UTC of the first day to 06 UTC after the period",
    ("tenmin", "sunshine_h"): "sum of the 10-minute values / 60, in UTC",
    ("nime", "precipitation_mm"): "sum of the days of 06 to 06 UTC by reference_date",
    ("nime_max", "fresh_snow_max_cm"): "the largest fresh_snow of one day (06 to 06 UTC) by reference_date",
}
HEADER = """# Published figures that this dataset must reproduce (skills/add-dataset, step 8). Generated by
# qa/tools/write_checks_meteoswiss.py from the figures of MeteoSwiss's climate bulletins
# (Klimabulletin) that match the stored data; notes, the figures that differ and why:
# qa/published_figures_meteoswiss.md. Collected 2026-11-15 (WP5.7): the yearly tables of 2015-2018,
# 2020, 2021, 2023 and 2024 and the monthly table of March 2025 were typed by Claude from the images
# of the PDFs (qa/published_figures_meteoswiss_typed.csv, with 19 figures from the record sentences
# of 2025-2026); the monthly tables of May 2025 to September 2026 were read from their text
# (qa/tools/klimabulletin_figures.py). The PDFs are kept in the swissgrid project
# (data/events/raw_nosync/).
# MeteoSwiss's periods are periods of its daily values: a month or a year is the days whose
# reference_date falls in it (UTC dates); precipitation sums the days of 06 to 06 UTC
# (precipitation_06utc), not the UTC days. Tolerance: half a unit of the last published digit,
# 0.05 for values to 0.1 and 0.5 for whole numbers.
checks:
"""


def period_text(p: str) -> str:
    return p if len(p) == 4 else f"{MONTHS[int(p[5:]) - 1]} {p[:4]}"


def where(dataset: str, variant: str, station: str, p: str) -> str:
    if len(p) == 4:
        a, b = f"{p}-01-01", f"{int(p) + 1}-01-01"
    else:
        y, m = int(p[:4]), int(p[5:])
        a, b = f"{y}-{m:02d}-01", (f"{y + 1}-01-01" if m == 12 else f"{y}-{m + 1:02d}-01")
    if variant in ("daily", "daily_06utc", "nime"):
        return f"station = '{station}'\n        AND reference_date >= DATE '{a}' AND reference_date < DATE '{b}'"
    h = "06" if variant == "hourly_06utc" else "00"
    return (f"station = '{station}'\n        AND delivery_start >= TIMESTAMPTZ '{a} {h}:00:00Z'"
            f" AND delivery_start < TIMESTAMPTZ '{b} {h}:00:00Z'")


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    urls = {r["file"]: r["url"] for r in csv.DictReader(open(QA / "klimabulletin_urls.csv", encoding="utf-8"))}
    figures = list(csv.DictReader(open(QA / "published_figures_meteoswiss_matched.csv", encoding="utf-8")))
    for dataset, plan in PLAN.items():
        out, names = [HEADER], set()
        for f in figures:
            if f["kind"] not in plan or not f["station"]:
                continue
            variant, table, expr = plan[f["kind"]]
            if dataset == "meteoswiss_smn_hourly" and f["period"] < "2018":
                continue
            got = f.get(variant)
            if got in (None, "") or abs(float(got) - float(f["value"])) > float(f["tolerance"]) + 1e-9:
                continue
            col, what, unit = KINDS[f["kind"]]
            name = f"{f['station'].lower()}_{f['period'].replace('-', '_')}_{col}"
            if name in names:
                continue
            names.add(name)
            page = f" p. {f['page']}" if f.get("page", "").isdigit() else (", record sentence" if f.get("page") else "")
            table_name = ("Jahreswerte an ausgewählten MeteoSchweiz-Messstationen" if len(f["period"]) == 4 else
                          "Monatswerte an ausgewählten Stationen")
            source = f"MeteoSwiss, Klimabulletin {f['period']}, {table_name}{page}, {f['station_name']}, {urls.get(f['file'], f['file'])}"
            question = (f"{what.capitalize()} at {f['station_name']} ({f['station']}) in {period_text(f['period'])}, "
                        f"{unit}: {HOW[(variant, f['kind'])]}")
            out.append(f"  - name: {name}\n"
                       f"    question: {q(question)}\n"
                       f"    sql: |\n      SELECT {expr}\n      FROM {dataset}.{table}\n      WHERE {where(dataset, variant, f['station'], f['period'])}\n"
                       f"    expected: {float(f['value']):g}\n"
                       f"    tolerance: {float(f['tolerance']):g}\n"
                       f"    source: {q(source)}\n")
        path = ROOT / "datasets" / dataset / "checks.yaml"
        if not names:  # nothing to check yet (e.g. the table is not backfilled): no file
            print(f"{dataset}: no figure matches, checks.yaml not written")
            continue
        path.write_text("".join(out), encoding="utf-8")
        print(f"{dataset}: {len(names)} checks --> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
